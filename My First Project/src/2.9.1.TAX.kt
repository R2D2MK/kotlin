fun main() {
    // Запрашиваем мощность двигателя в лошадиных силах
    print("Вводите мощность двигателя (л.с.): ")
    val power = readln().toInt()  // Читаем и преобразуем в число

    // Объявляем переменную под налоговую ставку (без начального значения)
    // Переменная tax типа Int будет проинициализирована в условных блоках
    var tax: Int

    // Определяем налоговую ставку в зависимости от мощности двигателя
    if (power <= 100) {
        tax = 10  // Ставка для мощности до 100 л.с.
    } else if (power < 150) {
        tax = 34  // Ставка для мощности от 101 до 149 л.с.
    } else if (power < 200) {
        tax = 49  // Ставка для мощности от 150 до 199 л.с.
    } else if (power < 250) {
        tax = 75  // Ставка для мощности от 200 до 249 л.с.
    } else {
        tax = 150 // Ставка для мощности от 250 л.с. и выше
    }

    // Вычисляем общую сумму налога
    val price = power * tax  // Умножаем мощность на ставку

    // Выводим подробную информацию о расчете
    println("Вид ТС: легковой автомобиль")
    println("Мощность двигателя: $power л.с.")
    println("Налоговая ставка: $tax руб./л.с.")
    println("Сумма налога: $price руб.")
}