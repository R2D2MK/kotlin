fun main() {
    // Читаем общее количество секунд из входных данных
    val seconds = readln().toInt()

    // Вычисляем количество полных часов:
    // 1. seconds / 60 - получаем общее количество минут
    // 2. (seconds / 60) / 60 - получаем количество часов (в 1 часе 60 минут)
    val hour = (seconds / 60) / 60

    // Вычисляем оставшиеся минуты после выделения часов:
    // (seconds / 60) % 60 - остаток от деления общего количества минут на 60
    val leftMinutes = (seconds / 60) % 60

    // Вычисляем оставшиеся секунды после выделения минут:
    // seconds % 60 - остаток от деления общего количества секунд на 60
    val leftSeconds = seconds % 60

    // Выводим результат в формате ЧАСЫ : МИНУТЫ : СЕКУНДЫ
    println("$hour : $leftMinutes : $leftSeconds")
}