fun main() {
    // Читаем текущую температуру из консоли и преобразуем в число
    val temperature = readln().toInt()

    // Проверяем условия для работы кондиционера
    if (temperature > 25) {
        // Если температура выше 25 градусов - включаем охлаждение
        println("The AC is on")
    } else if (temperature < 20) {
        // Если температура ниже 20 градусов - выключаем кондиционер
        println("The AC is off")
    } else {
        // Если температура между 20 и 25 градусами - режим ожидания
        println(" The AC is idle")
    }
}