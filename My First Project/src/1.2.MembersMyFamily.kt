fun main() {
    println(" My wife is Tanya")
    println(" My mother is Galya")
    println(" My cat is Simba")
    println(" My stepfather is Igor")
}

//Эта программа выводит на экран несколько строк текста.
//Описание программы:
//Функция _2_BasicSyntax.Collections.Nullable.main() — это точка входа в программу, с неё начинается выполнение любой Kotlin-программы.
//Внутри _2_BasicSyntax.Collections.Nullable.main() идут несколько вызовов функции println(), которая выводит текст на экран и переводит курсор на новую строку.

//Программа построчно выводит следующие фразы:
//
//" My wife is Tanya"
//" My mother is Galya"
//" My cat is Simba"
//" My stepfather is Igor"
//Каждая фраза выводится на новой строке благодаря использованию println().
