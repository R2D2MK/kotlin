fun main() {
    val value: Int = 72

       val result = when(value) {
        in 90 ..100 -> "A (Отлично)"
        in 75 .. 89 -> "B (Хорошо)"
        in 50..74 -> "C (Удовлетворительно)"
        in 20..49 -> "D (Плохо)"
        in 0..19 -> "F (Неудачно)"
        else -> "Ошибка: Некорректные баллы"
    }
    println("Ваши баллы: $value. Результат: $result")
}