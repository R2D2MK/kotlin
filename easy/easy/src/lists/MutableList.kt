package lists

/**
 * Пример работы со списками в Kotlin: MutableList и List.
 * Показывает:
 *   - как создавать и изменять MutableList
 *   - как работать с неизменяемыми List (пересоздание)
 *   - основные операции: добавление, удаление, замена, очистка.
 */

fun main() {
    // =================================================================================
    // 🔁 Часть 1: Работа с MutableList — список, который можно изменять после создания
    // =================================================================================

    val names = mutableListOf(
        "Maxim",
        "David",
        "Tatiana",
        "Simba"
    )
    println("🔹 Исходный список имён: $names")

    // ➕ Добавляем элемент в конец
    names.add("Galina")

    // 📌 Вставляем элемент в начало (по индексу 0)
    names.add(0, "Olga")

    // ❌ Удаляем элемент по значению (первое нашедшее)
    names.remove("Simba")

    // 🧹 Удаляем первый элемент (по индексу 0)
    names.removeAt(0) // Удаляем "Olga"

    // 🧹 Удаляем последний элемент (независимо от размера списка)
    names.removeAt(names.lastIndex)

    // ✏️ Заменяем элемент по индексу
    names[0] = "MK" // Заменяем "David" на "MK"

    // 🔍 Проверяем наличие элемента
    println("🔍 Содержит ли список 'David'? ${names.contains("David")}") // false — David удалён

    // 🗑️ Полностью очищаем список
    names.clear()
    println("🗑️ После очистки: $names (пустой список)")

    println() // Разделитель для читаемости

    // =================================================================================
    // ➕ Часть 2: Создание и заполнение MutableList<Int>
    // =================================================================================

    val numbersA = mutableListOf<Int>()         // Способ 1: тип указан явно
    val numbersB: MutableList<Int> = mutableListOf() // Способ 2: тип в объявлении переменной

    numbersA.add(666)
    numbersB.add(888)

    println("🔢 numbersA: $numbersA") // [666]
    println("🔢 numbersB: $numbersB") // [888]

    println() // Разделитель для читаемости

    // =================================================================================
    // 📜 Часть 3: Работа с неизменяемым List — пересоздание вместо изменения
    // =================================================================================

    // ❗ List — неизменяем. Нельзя добавить/удалить элементы. Можно только перезаписать.
    var immutableList = listOf<Int>()           // Начинаем с пустого списка
    var immutableListSecond: List<Int> = listOf() // Альтернативный синтаксис

    // Пересоздаём список с новыми значениями
    immutableList = listOf(1, 2, 3, 4, 5, 6)
    println("📜 immutableList после первого пересоздания: $immutableList")

    immutableListSecond = listOf(111, 222, 333, 444, 555, 666)
    println("📜 immutableListSecond: $immutableListSecond")

    // Снова пересоздаём — старый список заменяется новым
    immutableList = listOf(777, 888, 999, 1000, 2000, 3000)
    println("📜 immutableList после второго пересоздания: $immutableList")

    // 💡 Важно: сам список не изменяется — переменная просто начинает ссылаться на новый объект.
}