package lists

fun main() {
    // 📥 Создаём пустой список для хранения всех введённых строк
    val daysCounter = mutableListOf<String>()

    // 🔁 Бесконечный цикл: читаем ввод, пока не встретим стоп фразу
    while (true) {
        val userInput = readln()  // Читаем строку от пользователя

        // 🛑 Если введена стоп-фраза — выходим из цикла
        if (userInput == "Подсчёт продолжается" || userInput == "Подсчёт окончен") {
            break
        }
        // ➕ Иначе — добавляем строку в список (даже если это не "День прошёл")
        daysCounter.add(userInput)
    }

    // 🧮 Считаем оставшиеся дни: всего 14 минус количество введённых записей
    val daysLeft = 14 - daysCounter.size

    // 🖨️ Выводим результат
    println("До конца мероприятия (дней): $daysLeft")
}