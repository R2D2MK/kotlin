package split

fun main() {
    // Шаг 1: Просим пользователя ввести количество слов для проверки
    println("Введите количество слов для проверки:")
    val wordCount = readln().toInt()  // Читаем число и преобразуем в Int


    // Шаг 2: Для каждого слова (от 1 до wordCount) запускаем проверку
    for (i in 1..wordCount) {  // i — номер текущего слова (1, 2, 3...)
        println("Введите слово #$i:")  // Выводим приглашение для ввода
        val word = readln()           // Считываем само слово

        // Шаг 3: Предполагаем, что повторов нет — пока не докажем обратное
        var foundRepeat = false       // Флаг: нашли ли мы повтор?

        // Шаг 4: Проверяем каждую пару соседних букв в слове
        // Идём от первой буквы (индекс 0) до предпоследней (индекс word.length - 2)
        for (j in 0 until word.length - 1) {
            val currentChar = word[j]      // Текущая буква
            val nextChar = word[j + 1]     // Следующая буква

            // Шаг 5: Если текущая буква равна следующей — это повтор!
            if (currentChar == nextChar) {
                // Сразу выводим результат — не нужно хранить букву в переменной!
                println("$word: есть повторы: $currentChar")
                foundRepeat = true         // Запоминаем, что повтор найден
                break                      // Прерываем цикл — дальше проверять не нужно
            }
        }
        // Шаг 6: Если за весь цикл повтор не был найден — выводим "нет повторов"
        if (!foundRepeat) {
            println("$word: нет повторов")
        }
    }
}