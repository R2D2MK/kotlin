package split
/**
 * Программа для подсчёта общей стоимости снаряжения одного бойца.
 * Пользователь вводит количество предметов, затем построчно — название и цену каждого.
 * Программа суммирует все цены и выводит итог.
 */
fun main() {
    // Читаем строку вида "Количество предметов: N"
    val inputItemCount = readln().split(": ")
    // Берём вторую часть — это число предметов
    val finishCount = inputItemCount[1].toInt()
    // Создаём список для цен (изначально пустой)
    val equipment = mutableListOf<Int>()
    // Цикл: читаем по одному предмету снаряжения
    for (i in 1..finishCount) {
        // Читаем строку вида "Название: цена"
        val nameArmor = readln().split(": ")
        // Извлекаем цену (вторая часть) и преобразуем в число
        val priceArmor = nameArmor[1].toInt()
        // Добавляем цену в список
        equipment.add(priceArmor)
    }
    // Выводим сумму всех цен
    println("На основании полученных данных затраты на снаряжение одного бойца составляют ${equipment.sum()} кредитов")
}