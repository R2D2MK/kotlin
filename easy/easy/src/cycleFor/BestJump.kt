package cycleFor

fun main() {
    //Это как сказать: «У меня 5 спортсменов. Буду проверять 5 результатов».
    val items = 5

    //Это твоя тетрадь, где ты будешь писать лучший результат на данный момент.
    //Сначала она пуста, но чтобы начать, ты ставишь 0 — это стартовое значение.
    var maxItemValue = Int.MIN_VALUE

    //Это цикл — как турнир, где каждый спортсмен по очереди делает прыжок.
    //itemNumber — это номер спортсмена: 1, 2, 3, 4, 5.
    //Цикл выполнится ровно 5 раз — по одному разу для каждого.
    for (itemNumber in 1..items) {

        //Ты говоришь: «Спортсмен №1, введите свой результат».
        println("Введите значение элемента:")

        //Ты считываешь ввод — например, человек вводит 12.
        //.toInt() — превращает строку "12" в число 12, чтобы можно было сравнивать.
        val currentItemValue = readln().toInt()

        //💡Это самый важный момент.
        //Когда приходит первый спортсмен, у тебя ещё нет лучшего результата.
        //Поэтому ты просто берёшь его результат и записываешь как лучший.
        //Это называется инициализация максимума.
        // Как в жизни: первый прыжок — 3 метра. Пока это лучший результат. Даже если он маленький.
        if(itemNumber == 1) { // если это первый элемент в списке
            maxItemValue = currentItemValue // устанавливаем его максимальным
        }

        //Это основной закон сравнения.
        //Для всех спортсменов (включая первого) программа проверяет:
        //"Текущий результат больше, чем лучший на данный момент?"
        //Если да — обновляем лучший результат.
        //Если нет — ничего не делаем, идём к следующему.
        if (currentItemValue > maxItemValue) {
            maxItemValue = currentItemValue
        }
    }

    //Ты объявляешь победителя:
    //«Лучший результат — $maxItemValue метров!»
    println("Максимальное значение: $maxItemValue") // печатаем найденное максимальное значение
}

//💡 Главные идеи, которые нужно запомнить:
//Нельзя начать сравнивать, не имея "лучшего".
//→ Поэтому первый элемент берём как стартовый максимум.
//Цикл — это повторяющийся процесс.
//→ Каждый раз мы делаем одно и то же: вводим, сравниваем, при необходимости обновляем.
//maxItemValue — это "переменная-рекорд".
//→ Она хранит лучшее, что мы видели на данный момент.
//Не важно, какое число первое — алгоритм сам найдёт максимум.
//🛠️ Что можно улучшить (на будущее):
//Если все числа отрицательные, начинать с 0 — ошибка.
//Лучше: var maxItemValue = Int.MIN_VALUE — тогда любое число будет больше.

//✅ Итог, программа
//
//Запрашивает 5 чисел.
//Находит среди них самое большое.
//Использует простой, но мощный алгоритм — поиск максимума в цикле.
//Это как быть судьёй на соревнованиях:
//ты не знаешь, кто победит, но после каждого прыжка следишь за лидером.