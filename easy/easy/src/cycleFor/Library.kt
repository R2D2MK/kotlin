package cycleFor

fun main() {
    // Приглашение ввести количество книг
    println("Введите количество книг для проверки:")

    // Считываем общее количество книг для проверки
    val sumInputBooks = readln().toInt()

    // Счётчик для хранения количества книг, которые находятся "На руках"
    var booksInHands = 0

    // Цикл: обрабатываем каждую книгу по порядку
    // i — индекс от 0 до sumInputBooks - 1
    for (i in 0 until sumInputBooks) {
        // Запрашиваем название книги с номером (i + 1), так как нумерация с 1
        println("Введите название книги ${i + 1}:")

        // Считываем название книги (нужно только для следующего вывода)
        val bookName = readln()

        // Запрашиваем статус книги, используя её название в кавычках
        println("Введите статус книги \"$bookName\":")

        // Считываем статус книги
        val bookStatus = readln()

        // Проверяем, находится ли книга "На руках"
        if (bookStatus == "На руках") {
            // Если да — увеличиваем счётчик на 1
            booksInHands++
        }
    }

    // После обработки всех книг — выводим итоговое количество
    println("Количество книг со статусом \"На руках\": $booksInHands")
}