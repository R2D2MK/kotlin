package cycleFor

fun main() {
    // Выводим приглашение ввести месяц
    println("Введите месяц тура (Январь-Декабрь):")

    // Считываем название месяца (например, "Июль")
    val month = readln()

    // Выводим приглашение ввести туры
    println("Введите названия и цены 5 туров:")

    // Счётчик для цикла: сколько туров уже обработано (от 0 до 4)
    var sumTours = 0

    // Цикл: выполняем ровно 5 раз (для 5 туров)
    while (sumTours in 0..4) {
        // Считываем название текущего тура
        val nameTour = readln()

        // Считываем цену тура
        val priceTour = readln().toInt()

        // Проверяем, входит ли месяц в высокий сезон (июнь, июль, август)
        if (month in listOf("Июнь", "Июль", "Август")) {
            // Преобразуем значение в целое число
            val priceFinal = (priceTour * 1.2).toInt()
            // Выводим результат, округляя до целого числа (чтобы не было .0)
            println("Цена для тура \"$nameTour\": $priceFinal")
        } else {
            // Если сезон низкий — выводим цену без изменений (как строку)
            println("Цена для тура \"$nameTour\": $priceTour")
        }

        // Увеличиваем счётчик цикла на 1
        sumTours++
    }
}