package cycleFor


fun main() {
    val numbers = 9 // количество цифр для таблицы умножения

    println("Таблица умножения:")

    //Внешний цикл: for (number1 in 1..numbers)
//Это цикл, который будет перебирать числа от 1 до 9 (потому что numbers = 9).
//number1 — это первое число в умножении (например, 2 в выражении 2×3).
//🧩 Представь: сначала number1 = 1, потом number1 = 2, ..., и так до number1 = 9.
    for (number1 in 1..numbers) { // для каждой цифры
        // Внутренний цикл: for (number2 in 1..numbers)
        //Это цикл внутри цикла — вложенный цикл.
        //Он работает для каждого значения number1.
        //number2 — это второе число в умножении (например, 3 в выражении 2×3).
        //Он тоже перебирает числа от 1 до 9.
        //🔁 Получается:
        //Когда number1 = 1, внутренний цикл сделает 9 шагов:
        //1×1, 1×2, 1×3, ..., 1×9
        //Потом number1 = 2, и снова: 2×1, 2×2, ..., 2×9
        //И так до 9×9.
        for (number2 in 1..numbers) { // выполняем умножение на все другие
            println("${number1} x ${number2} = ${number1 * number2}") // и выводим результат
        }
        //🔹 Внешний цикл — это строки (по number1)
        //🔹 Внутренний цикл — это столбцы (по number2)
        //🔹 Каждая ячейка — это println с умножением
    }
}
