package cycleFor
//Ты — страж ворот в волшебный город.
//Перед тобой стоит список из 5 путников.
//У каждого в руках табличка с числом.
//Ты знаешь одно правило:
//Число 4 — запрещённое! Кто его принёс — не пропускается.
fun main() {
    val items = 5 // количество элементов для проверки

    //Это ключевое правило: число, которое нельзя пропускать.
    //Мы его вынесли в отдельную переменную, чтобы было легко изменить (например, на 7 или 13).
    val filterNumber = 4 // определяем какой номер запрещён

    //Это цикл — ты проверяешь по одному человеку, от первого до пятого.
    //itemNumber — это номер путника в очереди: 1, 2, 3, 4, 5.
    //Цикл выполнится ровно items раз.
    for (itemNumber in 1..items) {

        //Ты говоришь: «Следующий, покажи своё число!»
        //Это приглашение для пользователя.
        println("Введите значение элемента:")

        //Человек показывает число (например, 6).
        val inputNumber = readln().toInt()

        if (inputNumber != filterNumber) { // Если число не filterNumber ✅ "Можешь пройти!"
            println("Значение разрешено: $inputNumber") // печатаем обновленный список
        } else {
            println("Значение запрещено") // или выводим предупреждение
        }
    }
}