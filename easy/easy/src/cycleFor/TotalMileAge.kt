package cycleFor

fun main() {
    // Считываем количество поездок
    val sumMoves = readln().toInt()

    // Переменная для накопления общего пробега
    var totalMileAge = 0

    // Цикл: обрабатываем каждую поездку
    // Выполняется ровно sumMoves раз — по числу введённых перемещений
    for (i in 0 until sumMoves) {
        // Считываем пробег одной поездки (в километрах)
        val mileAge = readln().toInt()

        // Добавляем пробег текущей поездки к общей сумме
        totalMileAge += mileAge
    }

    // После цикла — анализ общего пробега
    // Проверяем, превышен ли порог в 100 000 км (пора на техобслуживание)
    if (totalMileAge > 100_000) {
        // Если пробег больше 100 тысяч — срочно нужно ТО
        println("Срочно требуется провести ТО")
    } else {
        // Иначе вычисляем, сколько километров осталось до следующего ТО
        val left = 100_000 - totalMileAge
        // Выводим оставшееся расстояние
        println("До следующего ТО: $left км")
    }
}