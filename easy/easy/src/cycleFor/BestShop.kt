package cycleFor

fun main() {
    // Запрашиваем у пользователя, сколько цветов скафандров нужно обработать
    println("Введите количество цветов скафандров:")
    // Считываем ввод и преобразуем его в целое число (например, 3)
    val inputColorValue = readln().toInt()
    // Цикл от 1 до указанного количества цветов (включительно)
    for (armorNumber in 1 .. inputColorValue) {
        // Запрашиваем название цвета для текущего номера
        println("Введите цвет #$armorNumber:")
        // Считываем введённый цвет как строку (например, "синий")
        val colorArmor = readln()
        // Выводим заголовок списка доступных моделей
        println("Список доступных моделей:")
        // Выводим модель: цвет + размер XS
        println(" - $colorArmor XS")
        // Выводим модель: цвет + размер M
        println(" - $colorArmor M")
        // Выводим модель: цвет + размер XL
        println(" - $colorArmor XL")
        // Пустая строка для визуального разделения между цветами
        println()
    }
}