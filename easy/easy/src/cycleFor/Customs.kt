package cycleFor

fun main() {
    // Выводим приглашение ввести количество ящиков
    println("Введите количество ящиков для проверки:")

    // Считываем число — сколько всего грузов нужно проверить
    val sumContainers = readln().toInt()

    // Цикл: обрабатываем каждый ящик, начиная с номера 1 до sumContainers включительно
    for (i in 1..sumContainers) {
        // Запрашиваем название груза с номером i (без пробела перед двоеточием — важно для Stepik!)
        println("Введите название груза #$i:")

        // Считываем название контейнера или ящика, введённое пользователем
        val nameContainers = readln()

        // Проверяем, является ли груз одним из особых: "Контейнер X" или "Ящик Z"
        if (nameContainers in listOf("Контейнер X", "Ящик Z")) {
            // Если да — выводим сообщение, что груз с этим номером задержан
            println("Груз #$i задержан!")
        }
    }
}