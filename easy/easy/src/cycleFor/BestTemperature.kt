package cycleFor

fun main() {
    // Выводим приглашение для пользователя
    println("Введите температуры за 7 дней:")

    // Количество дней недели (7)
    val dayCount = 7

    // Список названий дней недели по порядку (индекс 0 = Понедельник)
    val days = listOf("Понедельник", "Вторник", "Среда", "Четверг", "Пятница", "Суббота", "Воскресенье")

    // Переменная для хранения самой высокой температуры
    var maxTemp = Int.MIN_VALUE
    // Индекс дня с самой высокой температурой
    var maxDayIndex = -1

    // Переменная для хранения самой низкой температуры
    var minTemp = Int.MAX_VALUE
    // Индекс дня с самой низкой температурой
    var minDayIndex = -1

    // Цикл по индексам дней: от 0 до 6 (всего 7 итераций)
    for (dayIndex in 0 until dayCount) {
        // Считываем температуру с консоли и преобразуем в число
        val currentTemp = readln().toInt()

        // Если текущая температура ниже минимальной — обновляем минимум и запоминаем день
        if (currentTemp < minTemp) {
            minTemp = currentTemp
            minDayIndex = dayIndex
        }

        // Если текущая температура выше максимальной — обновляем максимум и запоминаем день
        if (currentTemp > maxTemp) {
            maxTemp = currentTemp
            maxDayIndex = dayIndex
        }
    }

    // Выводим результат: используем ${} чтобы получить название дня по индексу
    println("Самый теплый день: ${days[maxDayIndex]}")
    println("Самый холодный день: ${days[minDayIndex]}")
}