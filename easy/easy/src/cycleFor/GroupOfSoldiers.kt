package cycleFor

/**
 * Программа для расчёта количества боевых групп, которые можно сформировать из солдат.
 *
 * Правила:
 * - Полная группа: 8 солдат.
 * - Допускается только одна неполная группа, но только если в ней 3 и более солдат.
 * - Группа из 1 или 2 солдат — не формируется.
 */
fun main() {
    // Считываем общее количество солдат
    val soldiers = readln().toInt()

    // Рассчитываем количество полных групп по 8 человек
    val fullGroups = soldiers / 8

    // Определяем, сколько солдат останется после формирования полных групп
    val remainder = soldiers % 8

    // Неполная группа разрешена, только если в ней 3 или более солдата
    val hasSmallGroup = remainder >= 3

    // Общее количество групп: полные + (1, если можно сформировать неполную)
    val totalGroups = fullGroups + if (hasSmallGroup) 1 else 0

    // Выводим результат в требуемом формате
    println("Количество групп: $totalGroups")
}