fun main() {
    var foodBasketCost = 0  // Общая стоимость продуктовой корзины (начинается с 0)

    // Бесконечный цикл для чтения данных до команды остановки
    while (true) {
        val data = readln()  // Читаем ввод пользователя

        // Проверяем, не введена ли команда остановки
        if (data == "Продуктовая корзина пуста")
            break  // Выходим из цикла если получена команда остановки

        val itemPrice = data.toInt()  // Преобразуем ввод в цену товара (число)
        foodBasketCost += itemPrice   // Добавляем цену товара к общей сумме
    }

    // Выводим итоговую стоимость всех товаров
    println(foodBasketCost)
}