package function


fun main() {
    println("Список претендентов:")

    // Считываем строку со всеми участниками, прим: "Бибо - 479, Бобо - 486, Джонни - 498"
    val inputUsers = readln()

    // Разделяем строку на отдельные элементы (участников) по разделителю ", ".
    // Например, получаем массив ["Бибо - 479", "Бобо - 486", "Джонни - 498"]
    val users = inputUsers.split(", ").toTypedArray()

    // Вызываем функцию для поиска номера победителя.
    // Логика поиска инкапсулирована внутри функции getWinner.
    val winnerNumber = getWinner(users)

    // Выводим результат на экран, показывая, кто стал новым владельцем лота.
    println("Новый владелец лота - №${winnerNumber}")
}

/**
 * Ищет номер победителя аукциона по имени.
 *
 * @param users Массив строк, где каждая строка содержит имя и номер участника, разделенные " - ".
 * @return Номер участника по имени "Бибо". Если "Бибо" не найден, возвращается пустая строка.
 */
fun getWinner(users: Array<String>): String {
    // Переменная для хранения номера победителя.
    // Изначально она пустая, пока победитель не будет найден.
    var winnerNumber = ""

    // Проходим по каждому участнику в массиве.
    for (user in users) {
        // Разделяем строку участника на две части: имя и номер.
        // Например, "Бибо - 479" -> ["Бибо", "479"].
        val userData = user.split(" - ")
        val userName = userData[0] // Имя участника
        val userNumber = userData[1] // Номер участника

        // Проверяем, является ли текущий участник тем самым Бибо.
        if (userName == "Бибо") {
            // Если да, то сохраняем его номер.
            winnerNumber = userNumber
            // Мы нашли победителя, но продолжаем цикл до конца,
            // чтобы убедиться, что обрабатываем всех участников.
            // (В более продвинутом решении можно было бы прервать цикл,
            // но для простоты оставляем так.)
        } else {
            // Этот блок выполняется для всех, кто не Бибо.
            // Ключевое слово `continue` заставляет цикл перейти к следующей итерации,
            // игнорируя оставшийся код в текущей итерации.
            // Таким образом, мы не делаем ничего лишнего для "не-Бибо".
            continue
        }
    }

    // После завершения цикла возвращаем номер, который был сохранен,
    // когда был найден участник по имени "Бибо".
    // Если "Бибо" не был найден, вернется пустая строка, которая была
    // установлена в самом начале функции.
    return winnerNumber
}
