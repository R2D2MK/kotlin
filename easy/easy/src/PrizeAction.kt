fun main() {
    println("Выданные подарки:")  // Заголовок для вывода результатов

    // Бесконечный цикл для обработки действий клиентов
    while (true) {
        val action = readln()  // Читаем действие клиента из консоли

        // Условия выхода из цикла: пустая строка или команда закрытия системы
        if (action == "Система поощрений закрыта" || action == "")
            break  // Выходим из цикла

        // Обработка различных действий клиента и соответствующих поощрений/наказаний
        else if (action == "Оплата за 12 месяцев вперед") {
            println(" - Месяц бесплатного отопления")  // Награда за предоплату
        } else if (action == "Неуплата за 6 месяцев подряд") {
            println(" - Отключение отопления")  // Наказание за неуплату
        } else if (action == "День строительства дома клиента") {
            println(" - 1000 бонусных баллов на счёт клиента")  // Подарок на годовщину
        } else if (action == "Клиент не поздравил с Днём рождения компании") {
            println(" - Иск в суд на 100 000 кредитов")  // Штраф за непоздравление
        } else {
            print("")  // Игнорируем неизвестные действия (пустой вывод)
        }
    }
}