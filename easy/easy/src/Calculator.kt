// Главная функция программы - точка входа
fun main() {
    // Запрашиваем у пользователя первое число
    print("Enter first value: ")
    // Читаем ввод пользователя и преобразуем в число с плавающей точкой
    val firstValue = readln().toDouble()

    // Запрашиваем математическую операцию
    print("Enter mathematics operation (+ - / *): ")
    // Читаем ввод пользователя (символ операции)
    val operation = readln()

    // Запрашиваем у пользователя второе число
    print("Enter second value: ")
    // Читаем ввод пользователя и преобразуем в число с плавающей точкой
    val secondValue = readln().toDouble()

    // Вычисляем результат с помощью when-выражения (аналог switch-case)
    val result = when (operation) {
        // Сложение
        "+" -> firstValue + secondValue

        // Вычитание
        "-" -> firstValue - secondValue

        // Умножение (принимаем два варианта символов)
        "*", "x" -> firstValue * secondValue

        // Деление с проверкой деления на ноль
        "/" -> if (secondValue != 0.0)
            firstValue / secondValue  // Если делитель не ноль - выполняем деление
        else {
            // Если делитель равен нулю - выводим ошибку
            println("Ошибка: деление на ноль!")
            0.0  // Возвращаем 0.0 как результат при ошибке
        }

        // Обработка неизвестных операций
        else -> {
            // Сообщаем пользователю о неизвестной операции
            println("Неизвестная операция: $operation")
            0.0  // Возвращаем 0.0 как результат при ошибке
        }
    }

    // Выводим итоговый результат вычислений в формате: число операция число = результат
    println("$firstValue $operation $secondValue = $result")
}