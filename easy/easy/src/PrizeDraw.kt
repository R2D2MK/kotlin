fun main() {
    // Читаем количество гостей из входных данных
    val guests = readln().toInt()

    // Проверяем, что количество гостей неотрицательное
    if (guests == 0 ) {
        print("Затраты на призы = 0") // Если гостей нет - затраты 0
        return     // Завершаем программу
    }

    // Используем формулу суммы арифметической прогрессии:
    // S = n/2 * (2*a1 + (n-1)*d)
    // где:
    // n - количество гостей (членов прогрессии)
    // a1 = 1000 - первый член прогрессии (чек первого гостя)
    // d = 100 - разность прогрессии (увеличение для каждого следующего гостя)

    val firstCheck = 1000 // Чек для первого гостя
    val increment = 100 // Увеличение для каждого следующего гостя

    // Вычисляем общую сумму по формуле суммы арифметической прогрессии
    val totalCost = guests * (2 * firstCheck + (guests - 1) * increment) / 2

    // Выводим результат
    print(totalCost)
}