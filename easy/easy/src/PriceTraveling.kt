fun main() {
    // Переменная для хранения общей "стоимости" движений
    var price = 0

    // Запускаем бесконечный цикл, чтобы обрабатывать ввод команд до остановки
    while (true) {
        // Считываем команду движения от пользователя
        val motion = readln()

        // Проверяем, является ли введённая команда командой завершения
        if (motion == "Стоп") {
            break // Если да — выходим из цикла
        }
        // Если команда — "Прямо", увеличиваем стоимость на 1
        else if (motion == "Прямо") {
            price++
        }
        // Если команда — "Вправо" или "Влево", увеличиваем стоимость на 2
        else if (motion == "Вправо" || motion == "Влево") {
            price += 2
        }
        // Если команда — "Круговая", увеличиваем стоимость на 3
        else if (motion == "Круговая") {
            price += 3
        }
        // Если введена неизвестная команда, она игнорируется (можно добавить предупреждение при необходимости)
    }

    // Выводим итоговую стоимость всех выполненных движений
    println(price)
}