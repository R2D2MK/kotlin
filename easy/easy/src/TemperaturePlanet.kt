fun main() {
    // Считываем начальную температуру, введённую пользователем
    var temperature = readln().toInt()

    // Счётчик дней, прошедших с начала терраформирования
    var days = 0

    // Цикл: продолжаем, пока температура МЕНЬШЕ ИЛИ РАВНА 25
    while (temperature <= 25) {
        temperature += 3  // увеличиваем температуру на 3 градуса
        days += 2         // проходит 2 дня
    }

    // Выводим общее количество дней
    println(days)
}