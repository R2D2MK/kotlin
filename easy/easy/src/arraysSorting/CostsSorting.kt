package arraysSorting
/**
 * Задача: Сортировка массива чисел по возрастанию.
 * Метод: Простая сортировка перебором (через два вложенных цикла).
 * Для обучения: Этот код показывает, КАК именно происходит сортировка "вручную".
 */
fun main() {
    // Шаг 1: Запрашиваем количество чисел
    val count = readln().toInt()
    // Создаём массив целых чисел нужной длины
    val array = Array<Int>(count) { 0 }

    // Шаг 2: Заполняем массив числами
    for(index in array.indices) {
        array[index] = readln().toInt()
    }
    // ───────────────────────────────
    // Шаг 3: Сортируем массив по возрастанию
    // ───────────────────────────────
    // Идея: для каждой пары чисел — если левое > правого, меняем их местами.
    // Так постепенно меньшие числа "всплывают" в начало.

    for(i in array.indices) {               // i — индекс текущего числа
        for(j in array.indices) {           // j — индекс числа, с которым сравниваем
            if(array[i] < array[j]) {
                // Меняем местами numbers[i] и numbers[j]
                val tempCost = array[i]     // сохраняем текущее число
                array[i] = array[j]         // на место i ставим большее число
                array[j] = tempCost         // на место j — меньшее
            }
        }
    }

    for(cost in array) {
        println(cost)
    }
}