fun main() {
    // Считываем размер поля (N × N) — например, 3 или 5
    val boardSize = readln().toInt()

    // Внешний цикл: проходим по каждой строке поля (от 1 до boardSize)
    for (row in 1..boardSize) {

        // Внутренний цикл: проходим по каждому столбцу в текущей строке
        for (col in 1..boardSize) {

            // Определяем, какой символ выводить: ■ или □
            // Используем сумму номера строки и столбца
            // Если сумма (row + col) чётная — ставим ■, если нечётная — □
            // Это создаёт шахматное чередование
            if ((row + col) % 2 == 0) {
                print("■")  // Чёрная клетка
            } else {
                print("□")  // Белая клетка
            }
        }

        // После того как строка полностью выведена, переходим на новую строку
        println()
    }
}