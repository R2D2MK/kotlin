package arrays
fun main() {

    val stringArray = arrayOf("Звёздный крейсер", "тяжелый линкор", "легкий фрегат", "корвет")
    val numbersInt = intArrayOf(150, 260, 380, 740, 999)
    val numbersDouble = doubleArrayOf(150.5, 260.0, 380.0, 740.0, 999.9)
    val booleanValue = booleanArrayOf(true, false, false, true)

    println(stringArray)
    println(numbersInt)
    println(numbersDouble)
    println(booleanValue)

}