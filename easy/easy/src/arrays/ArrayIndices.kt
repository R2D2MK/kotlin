package arrays

fun main() {
    // Считываем количество элементов и преобразуем в число
    val count = readln().toInt() // команда toInt() приводит значение String к Int

    // Создаем массив строк указанного размера, инициализируя пустыми строками
    val array = Array<String>(count) { "" } // создает массив, каждый из элементов является пустой строкой

    // Проходим по всем индексам массива
    for (index in array.indices) {
        // На каждой итерации считываем имя с клавиатуры и записываем его в соответствующую ячейку массива
        array[index] = readln()
    }

    // Проходим по массиву для формирования пар "текущий элемент - следующий элемент"
    for (index in array.indices) {
        // Останавливаемся на предпоследнем элементе, чтобы не выйти за границы массива
        if (index == array.size - 1) break // предотвращаем обращение к array[index + 1] для последнего элемента

        // Выводим пару: текущий элемент и следующий за ним элемент
        println("${array[index]} - ${array[index + 1]}")
    }
}