package arrays

fun main() {
    // Считываем количество гостей как строку и преобразуем её в целое число
    val number_of_guests = readln().toInt()

    // Создаём массив строк размером number_of_guests, изначально заполняя каждую ячейку пустой строкой
    val guests = Array<String>(number_of_guests) { "" }

    // Проходим по всем индексам массива
    for (index in guests.indices) {
        // На каждой итерации считываем имя гостя с клавиатуры и записываем его в соответствующую ячейку массива
        guests[index] = readln()
    }

    // Выводим заголовок перед списком
    println("Гости:")

    // Снова проходим по всем индексам массива, чтобы вывести имена гостей
    for (index in guests.indices) {
        // Выводим номер гостя (индекс + 1, чтобы нумерация начиналась с 1, а не с 0) и его имя
        println("${index + 1}. ${guests[index]}")
    }
}