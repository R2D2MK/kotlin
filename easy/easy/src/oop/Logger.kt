package oop

// 🔑 Ключевое слово 'object' автоматически создает ОДИНОЧКУ (Singleton).
// Это гарантирует, что у Logger всегда будет только один экземпляр в программе.
object Logger {

    // Функция log() принимает строку (message) и отвечает за ФОРМАТИРОВАНИЕ и вывод.
    // Это единственный "публичный" способ записи логов.
    fun log(message: String) {
        // Используем строковый шаблон ($) для вывода в требуемом формате.
        println("Log: $message")
    }
}

// Главная точка входа в программу.
fun main() {
    // 1. Читаем ПЕРВУЮ строку из консоли (количество логов 'n').
    // readln() безопасно читает строку, а toInt() преобразует её в число.
    val inputCount = readln().toInt()

    //  Используем цикл 'repeat' для ПОВТОРЕНИЯ действий.
    repeat(inputCount){
        val inputText = readln()

        // Используем наш Singleton-объект Logger для вывода сообщения.
        // Вызов метода через имя объекта: Logger.log(...)
        Logger.log(inputText)
    }
}