package testFinal

fun main() {

val n: Int = readln().toInt() // количество чисел в последовательности

var number: Int

var max = -1000001 // значение 0 заведомо меньше возможных значений последовательности


for (i in 0 until n) {
    number = readln().toInt() // очередное число последовательности
    if (number > max) // сравниваем текущее число с мах
    {
        max = number // если больше, то обновляем мах
    }
}

println(max) // после просмотра всех чисел последовательности, выводим максимальное значение
}